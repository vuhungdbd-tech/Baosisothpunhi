/**
 * Tiện ích xử lý thông tin học sinh và danh sách lớp
 */

export function inferGenderFromName(fullName: string): 'Nam' | 'Nữ' {
  if (!fullName) return 'Nam';
  const name = fullName.toLowerCase();
  const femaleKeywords = ['thị', 'thi', 'hoa', 'hương', 'huong', 'lan', 'mai', 'huyền', 'huyen', 'ngọc', 'ngoc', 'trang', 'linh', 'nga', 'hà', 'ha', 'nhung', 'phương', 'phuong', 'thảo', 'thao', 'yến', 'yen'];
  const words = name.split(/\s+/);
  if (words.some((w) => femaleKeywords.includes(w))) {
    return 'Nữ';
  }
  return 'Nam';
}

export function resolveStudentGender(gender?: string, fullName?: string): 'Nam' | 'Nữ' {
  if (gender) {
    const g = gender.trim().toLowerCase();
    if (g === 'nữ' || g === 'nu' || g === 'female' || g === 'f') return 'Nữ';
    if (g === 'nam' || g === 'male' || g === 'm') return 'Nam';
  }
  if (fullName) {
    return inferGenderFromName(fullName);
  }
  return 'Nam';
}

export function isValidStudentAddress(address?: string): boolean {
  if (!address) return false;
  const a = address.trim().toLowerCase();
  return a.length > 0 && a !== '-' && a !== 'null' && a !== 'undefined' && a !== 'chưa có';
}

export function cleanStudentAddress(address?: string): string {
  if (!address) return '';
  const a = address.trim();
  if (a === '-' || a.toLowerCase() === 'null' || a.toLowerCase() === 'undefined') return '';
  return a;
}

export function isAutoGeneratedSeedStudent(student: any): boolean {
  if (!student) return false;
  return Boolean(
    student.is_seed ||
    student.is_auto_generated ||
    (typeof student.id === 'string' && (student.id.startsWith('seed_') || student.id.startsWith('auto_')))
  );
}

export function isStudentInClass(
  studentOrClassId: any,
  targetClassId?: string,
  targetClassName?: string
): boolean {
  if (!studentOrClassId) return false;
  
  if (typeof studentOrClassId === 'string') {
    const cid = studentOrClassId.trim();
    if (targetClassId && cid === targetClassId.trim()) return true;
    if (targetClassName && cid.toLowerCase() === targetClassName.trim().toLowerCase()) return true;
    return false;
  }

  if (typeof studentOrClassId === 'object') {
    const sCid = studentOrClassId.class_id;
    if (sCid && targetClassId && sCid === targetClassId) return true;
    if (studentOrClassId.className && targetClassName && studentOrClassId.className.toLowerCase() === targetClassName.toLowerCase()) return true;
    return false;
  }

  return false;
}

